"""
Generate docs/nodes.md from the node registry.

Runs outside Fusion: the adsk modules are stubbed so node specs can be read.
Usage: python3 scripts/generate_node_docs.py [--check]
  --check  exit 1 if docs/nodes.md is out of date instead of writing it
"""

import sys
import types
from pathlib import Path
from unittest.mock import MagicMock

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / 'docs' / 'nodes.md'

# Stub the Fusion API before anything in backend imports it
adsk = types.ModuleType('adsk')
adsk.core = MagicMock()
adsk.fusion = MagicMock()
sys.modules.update({'adsk': adsk, 'adsk.core': adsk.core, 'adsk.fusion': adsk.fusion})
sys.path.insert(0, str(REPO_ROOT))

from backend.nodes import NodeRegistry  # noqa: E402


def _cell(value) -> str:
    if value is None or value == '':
        return ''
    if isinstance(value, float):
        value = f'{value:g}'
    if isinstance(value, (list, tuple)):
        value = ', '.join(str(v) for v in value)
    return str(value).replace('|', '\\|').replace('\n', ' ')


def _range(port: dict) -> str:
    lo, hi = port.get('minValue'), port.get('maxValue')
    if lo is None and hi is None:
        return ''
    return f"{_cell(lo) or '−∞'} … {_cell(hi) or '∞'}"


def _port_table(ports: list, with_defaults: bool) -> list:
    if not ports:
        return ['_None_', '']
    if with_defaults:
        lines = ['| Input | Type | Default | Range / options | Description |',
                 '|---|---|---|---|---|']
    else:
        lines = ['| Output | Type | Description |', '|---|---|---|']
    for port in ports:
        name = f"**{_cell(port.get('label') or port['name'])}**"
        port_type = f"`{port['type']}`"
        unit = {'length': ' (cm)', 'angle': ' (degrees)'}.get(port.get('unit'), '')
        port_type += unit
        description = _cell(port.get('description'))
        if with_defaults:
            options = _cell(port.get('enumLabels') or port.get('enumOptions')) or _range(port)
            lines.append(f"| {name} | {port_type} | {_cell(port.get('defaultValue'))} | {options} | {description} |")
        else:
            lines.append(f'| {name} | {port_type} | {description} |')
    lines.append('')
    return lines


def render() -> str:
    NodeRegistry.initialize(None)
    specs = NodeRegistry.get_all_specs()
    sections = NodeRegistry.get_menu_sections()

    by_section = {}
    for spec in specs:
        by_section.setdefault(spec['menu_category'], []).append(spec)
    ordered = [s for s in sections if s in by_section] + sorted(s for s in by_section if s not in sections and not s.startswith('_'))

    lines = ['# Node reference', '',
             '<!-- Generated by scripts/generate_node_docs.py — do not edit by hand. -->', '',
             f'{len(specs)} nodes, grouped as they appear in the Add Node menu.', '']
    lines += [f'- [{s.title()}](#{s.lower()})' for s in ordered]
    lines.append('')

    for section in ordered:
        lines += [f'## {section.title()}', '']
        for spec in sorted(by_section[section], key=lambda s: s['name']):
            lines += [f"### {spec['name']}", '']
            if spec.get('description'):
                lines += [spec['description'], '']
            lines += _port_table(spec['inputs'], with_defaults=True)
            lines += _port_table(spec['outputs'], with_defaults=False)

    return '\n'.join(lines).rstrip() + '\n'


def main() -> int:
    content = render()
    if '--check' in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f'{OUTPUT.relative_to(REPO_ROOT)} is out of date; run scripts/generate_node_docs.py')
            return 1
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(content)
    print(f'Wrote {OUTPUT.relative_to(REPO_ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
